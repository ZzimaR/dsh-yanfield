import { build } from "esbuild"
import { existsSync, statSync } from "node:fs"
import { mkdir, readdir, readFile, writeFile, rm } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { spawn } from "node:child_process"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const vendor = path.join(root, "vendor", "yanfield")
const apiRoot = path.join(vendor, "app", "api")

function cssModulePlugin() {
  return {
    name: "yanfield-css-module",
    setup(build) {
      build.onResolve({ filter: /\.module\.css$/ }, (args) => ({
        path: path.resolve(args.resolveDir, args.path),
        namespace: "cssmod",
      }))
      build.onLoad({ filter: /.*/, namespace: "cssmod" }, async (args) => {
        const css = await readFile(args.path, "utf8")
        const names = new Set()
        for (const match of css.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) names.add(match[1])
        const map = Object.fromEntries([...names].map((name) => [name, name]))
        return {
          contents: `export default ${JSON.stringify(map)}\n`,
          loader: "js",
        }
      })
    },
  }
}
function atAliasPlugin() {
  return {
    name: "yanfield-at",
    setup(build) {
      build.onResolve({ filter: /^@\// }, (args) => {
        const base = path.join(vendor, args.path.slice(2))
        const candidates = [
          base,
          ...[".tsx", ".ts", ".jsx", ".js", ".mjs", ".css"].map((ext) => base + ext),
          ...["tsx", "ts", "js"].map((ext) => path.join(base, `index.${ext}`)),
        ]
        const found = candidates.find((candidate) => existsSync(candidate) && statSync(candidate).isFile())
        if (!found) return { errors: [{ text: `找不到 ${args.path}` }] }
        return { path: found }
      })
    },
  }
}

async function walk(dir, acc = []) {
  const entries = await readdir(dir, { withFileTypes: true })
  for (const entry of entries) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) await walk(full, acc)
    else if (entry.name === "route.ts") acc.push(full)
  }
  return acc
}

function patternOf(file) {
  const rel = path.relative(apiRoot, file).replaceAll("\\", "/")
  const parts = rel.split("/").slice(0, -1).map((part) => part.startsWith("[") && part.endsWith("]") ? `:${part.slice(1, -1)}` : part)
  return `/api/${parts.filter(Boolean).join("/")}`
}

async function generateRoutes() {
  const files = (await walk(apiRoot)).sort()
  const lines = ["// Generated by scripts/build.mjs. Do not edit."]
  files.forEach((file, index) => {
    const rel = path.relative(path.join(root, "src", "generated"), file).replaceAll("\\", "/")
    lines.push(`import * as route${index} from ${JSON.stringify(rel)}`)
  })
  lines.push("export const routes = [")
  files.forEach((file, index) => {
    lines.push(`  { pattern: ${JSON.stringify(patternOf(file))}, handlers: route${index} },`)
  })
  lines.push("]")
  lines.push("")
  const out = path.join(root, "src", "generated", "routes.js")
  await mkdir(path.dirname(out), { recursive: true })
  await writeFile(out, lines.join("\n"))
  console.log(`[dsh-yanfield] routes ${files.length}`)
}

function run(command, args) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { cwd: root, stdio: "inherit", shell: process.platform === "win32" })
    child.on("exit", (code) => code === 0 ? resolve() : reject(new Error(`${command} exited ${code}`)))
  })
}

await generateRoutes()
await run("npx", ["@tailwindcss/cli", "-i", "client/app.css", "-o", "client/styles.generated.css", "--minify"])
const statusBarCss = await readFile(path.join(vendor, "components", "editor", "EditorStatusBar.module.css"), "utf8")
await writeFile(path.join(root, "client", "styles.generated.css"), `\n${statusBarCss}`, { flag: "a" })

await build({
  entryPoints: [path.join(root, "client", "index.tsx")],
  outfile: path.join(root, "dist", "client.js"),
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: "chrome120",
  jsx: "automatic",
  external: ["react", "react/jsx-runtime", "react-dom", "react-dom/client"],
  alias: {
    "next/link": path.join(root, "client", "shims", "link.tsx"),
    "next/navigation": path.join(root, "client", "shims", "navigation.ts"),
  },
  plugins: [atAliasPlugin(), cssModulePlugin()],
  loader: { ".css": "text" },
  minify: true,
  legalComments: "none",
  logLevel: "info",
  banner: {
    js: 'window.__ModuleLoader__.load({id:"dsh-yanfield",factory:(require)=>{const module={exports:{}};const exports=module.exports;',
  },
  footer: { js: "return module.exports}})" },
})

await build({
  entryPoints: [path.join(root, "src", "host.ts")],
  outfile: path.join(root, "dist", "host.js"),
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  alias: {
    "next/server": path.join(root, "src", "shims", "next-server.ts"),
  },
  plugins: [atAliasPlugin()],
  legalComments: "none",
  logLevel: "info",
  banner: { js: "// dsh-yanfield host bundle. Built by scripts/build.mjs." },
})
await rm(path.join(root, "dist", "client.css"), { force: true })
console.log("[dsh-yanfield] built dist/host.js and dist/client.js")
